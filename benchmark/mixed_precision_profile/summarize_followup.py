"""Build the markdown tables for PROFILE_FINDINGS.md sections 9-11 from results/.

  python summarize_followup.py > results/followup_tables.md
"""
import glob, json, os, re, statistics, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "results")
sys.path.insert(0, HERE)
import analyze_trace as at  # noqa: E402

CAT_LABEL = {"P1g": "P1g", "P2": "P2", "P3": "P3", "P4": "P4", "K1": "K1", "M": "M", "I": "I"}


def breakdown_rows(names):
    out = []
    for n in names:
        d = os.path.join(R, "followup_breakdown", n)
        if not os.path.exists(os.path.join(d, "DONE")) and not glob.glob(os.path.join(d, "trace", "*.gz")):
            continue
        tr = sorted(glob.glob(os.path.join(d, "trace", "*.trace.json.gz")))
        if not tr:
            continue
        wl = "extend" if n.split("_")[-1].startswith("W2") else "decode"
        res = at.analyze(tr[0], wl, kv_mode=n.split("_")[0])
        res["name"] = n
        out.append(res)
    return out


def fmt_breakdown(rows, title):
    print(f"\n#### {title}\n")
    print("| capture | steps | step ms | P1g | P2 | P3 | P4 | K1 | M | I | P1 CPU ms | prep ms (P1g+P2+P3+P4+I) | K1 % wall | M % wall | prep % wall |")
    print("| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
    for r in rows:
        ms = r["ms"]
        wall = sum(ms[k] for k in at.ORDER) + ms["I"]
        prep = ms["P1g"] + ms["P2"] + ms["P3"] + ms["P4"] + ms["I"]
        print(f"| {r['name']} | {r['steps']} | {wall:.2f} | {ms['P1g']:.2f} | {ms['P2']:.2f} | {ms['P3']:.2f} | "
              f"{ms['P4']:.2f} | {ms['K1']:.2f} | {ms['M']:.2f} | {ms['I']:.2f} | {r['cpu_ms'].get('_p1_total', float('nan')):.2f} | "
              f"{prep:.2f} | {100*ms['K1']/wall:.1f}% | {100*ms['M']/wall:.1f}% | {100*prep/wall:.1f}% |")
    print("\nGPU-time view (P2+P3+P4+K1+M = 100%, P1g listed separately):\n")
    print("| capture | P1g % | P2 % | P3 % | P4 % | K1 % | M % |")
    print("| --- | ---: | ---: | ---: | ---: | ---: | ---: |")
    for r in rows:
        ms = r["ms"]
        g = ms["P2"] + ms["P3"] + ms["P4"] + ms["K1"] + ms["M"]
        print(f"| {r['name']} | {100*ms['P1g']/g:.2f} | {100*ms['P2']/g:.2f} | {100*ms['P3']/g:.2f} | "
              f"{100*ms['P4']/g:.2f} | {100*ms['K1']/g:.1f} | {100*ms['M']/g:.1f} |")


def point_summary(name):
    p = os.path.join(R, "followup_points", name, "summary.txt")
    if not os.path.exists(p):
        return None
    lines = open(p).read().splitlines()
    head = lines[0] if lines else ""
    rows = []
    for ln in lines[2:]:
        f = ln.split()
        if len(f) >= 9 and f[0] in ("bf16", "fp8", "tri"):
            rows.append(dict(mode=f[0], conc=f[1], nreq=f[2], out=f[3], tot=f[4], tpot=f[5], ttft=f[6], run=f[7], status=f[8]))
    extra = [ln for ln in lines[2:] if not (ln.split() and ln.split()[0] in ("bf16", "fp8", "tri"))]
    return dict(head=head, rows=rows, extra=extra, done=os.path.exists(os.path.join(R, "followup_points", name, "DONE")))


def vllm_summary(name):
    d = os.path.join(R, "followup_vllm", name)
    j = os.path.join(d, "bench.json")
    if not os.path.exists(j):
        return None
    b = json.load(open(j))
    return dict(out=b.get("output_throughput"), tot=b.get("total_token_throughput"),
                tpot=b.get("mean_tpot_ms"), ttft=b.get("mean_ttft_ms"), n=b.get("completed"),
                in_tok=b.get("total_input_tokens"), out_tok=b.get("total_output_tokens"))


def main():
    print("<!-- generated by summarize_followup.py -->")
    print("\n### Step-time breakdown, Qwen3-8B")
    fmt_breakdown(breakdown_rows(["bf16_W1", "bf16_rep_W1", "fp8_W1", "tri_W1"]), "W1 decode, captured at the start of decode (KV about 1.1k tokens per request)")
    fmt_breakdown(breakdown_rows(["bf16_mid_W1", "fp8_mid_W1", "tri_mid_W1"]), "W1 decode, captured mid-run (KV about 2k tokens per request)")
    fmt_breakdown(breakdown_rows(["bf16_W2", "fp8_W2", "tri_W2"]), "W2 prefill steps")
    print("\n### Step-time breakdown, Qwen3-32B capacity-bound decode")
    fmt_breakdown(breakdown_rows(["bf16_q32_S4096", "fp8_q32_S4096", "tri_q32_S4096"]), "4096/1024, concurrency 32")

    print("\n### Engine baselines, Qwen3-8B, fixed lengths\n")
    print("| engine | KV | workload | output tok/s | total tok/s | TPOT ms | TTFT ms | requests |")
    print("| --- | --- | --- | ---: | ---: | ---: | ---: | ---: |")
    for kv in ("bf16", "fp8"):
        for wl in ("W1", "W2"):
            s = point_summary(f"g3_sglang_{kv}_{wl}")
            if s and s["rows"]:
                r = s["rows"][0]
                print(f"| SGLang | {kv} | {wl} | {r['out']} | {r['tot']} | {r['tpot']} | {r['ttft']} | {r['nreq']} |")
            v = vllm_summary(f"vllm_{kv}_{wl}")
            if v:
                print(f"| vLLM | {kv} | {wl} | {v['out']:.1f} | {v['tot']:.1f} | {v['tpot']:.2f} | {v['ttft']:.1f} | {v['n']} |")

    print("\n### Qwen3-32B points\n")
    for name in ("q32_bf16_sweep", "q32_fp8_sweep", "q32_tri005_sweep", "q32_tri085_sweep",
                 "q32_bf16_W2", "q32_fp8_W2", "q32_tri005_W2", "q32_tri085_W2"):
        s = point_summary(name)
        if not s:
            continue
        print(f"\n`{name}` ({'complete' if s['done'] else 'INCOMPLETE'}): {s['head']}\n")
        print("| conc | requests | output tok/s | total tok/s | TPOT ms | TTFT ms | avg running | status |")
        print("| ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |")
        for r in s["rows"]:
            print(f"| {r['conc']} | {r['nreq']} | {r['out']} | {r['tot']} | {r['tpot']} | {r['ttft']} | {r['run']} | {r['status']} |")
        for ln in s["extra"]:
            print(f"\n    {ln}")


if __name__ == "__main__":
    main()
